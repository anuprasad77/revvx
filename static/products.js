// Dynamically load PapaParse for CSV processing
const papaScript = document.createElement('script');
papaScript.src = "https://cdnjs.cloudflare.com/ajax/libs/PapaParse/5.4.1/papaparse.min.js";
papaScript.onload = () => {
    Papa.parse(GOOGLE_SHEET_CSV_URL, {
        download: true,
        header: true,
        skipEmptyLines: true,
        complete: function(results) {
            processCSVData(results.data);
            if (typeof renderProductsList === 'function') renderProductsList();
            if (typeof renderProductDetails === 'function') renderProductDetails(); // Re-render if on product.html
        },
        error: function(error) {
            console.error("Error loading Google Sheet CSV:", error);
        }
    });
};
document.head.appendChild(papaScript);
